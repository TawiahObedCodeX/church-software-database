import { round2 } from '../utils/contributions'

/** ISO yyyy-mm-dd for a date N days before today. */
function daysAgo(n) {
  const date = new Date()
  date.setDate(date.getDate() - n)
  return date.toISOString().slice(0, 10)
}

/** Stable-ish id generator. Kept counter-based so ids stay readable. */
let paymentSeq = 0
function payment(amount, day, method, reference = '', note = '') {
  paymentSeq += 1
  const date = daysAgo(day)

  /* Spread entries across a working day so the time column is not all
     identical, and so same-day installments still sort deterministically. */
  const hour = 8 + ((paymentSeq * 3) % 10)
  const minute = (paymentSeq * 17) % 60

  return {
    id: `PAY-${String(1000 + paymentSeq)}`,
    amount: round2(amount),
    date,
    timestamp: new Date(
      `${date}T${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}:00`,
    ).toISOString(),
    method,
    reference: reference || `REF-${1000 + paymentSeq}`,
    note,
  }
}

